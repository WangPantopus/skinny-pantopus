#!/usr/bin/env node
// pgTAP executes each behavioral SQL contract inside one outer transaction.
// Generate committed wrappers so Supabase's isolated test runner needs no
// repository paths or psql includes outside supabase/tests.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const source = path.join(__dirname, 'contracts');
const output = path.join(root, 'supabase/tests');
const check = process.argv[2] === '--check';
if (process.argv.length > 3 || (process.argv[2] && !check)) throw new Error('Use --check or no arguments');
const marker = '-- Generated by scripts/db/sync-sql-contracts.cjs; edit the source contract.\n';
if (!check) fs.mkdirSync(output, { recursive: true });
const names = fs.readdirSync(source).filter(name => name.endsWith('.sql')).sort();
for (const name of names) {
  const sql = fs.readFileSync(path.join(source, name), 'utf8');
  if ((sql.match(/^BEGIN;$/gm) || []).length !== 1 || (sql.match(/^ROLLBACK;$/gm) || []).length !== 1 || sql.includes('$contract$')) {
    throw new Error(`Contract needs exactly one outer transaction: ${name}`);
  }
  const body = sql.replace(/^(BEGIN|ROLLBACK);\n/gm, '');
  const generated = marker + `-- Source: scripts/db/contracts/${name}\nBEGIN;\n` +
    "CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;\nSET LOCAL search_path = public, extensions, pg_catalog;\nSELECT plan(1);\n" +
    `SELECT lives_ok($contract$\n${body}\n$contract$, '${name.replaceAll("'", "''")}');\nSELECT * FROM finish();\nROLLBACK;\n`;
  const target = path.join(output, name.replace(/\.sql$/, '.test.sql'));
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) throw new Error(`Regenerate SQL contract: ${name}`);
  } else fs.writeFileSync(target, generated);
}
for (const file of fs.readdirSync(output)) {
  if (file.endsWith('.test.sql') && fs.readFileSync(path.join(output, file), 'utf8').startsWith(marker) &&
      !names.includes(file.replace(/\.test\.sql$/, '.sql'))) throw new Error(`Remove stale generated contract: ${file}`);
}
console.log(`${names.length} pgTAP contract wrappers ${check ? 'verified' : 'generated'}`);
